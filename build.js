/* Build script: concatenates src/ into dist/Balloonist.jsx.
   - core modules load in a fixed order
   - features are discovered from src/features/*.jsx (sorted by filename)
   - the result is one ExtendScript file for the InDesign Scripts Panel

   Usage: node build.js            (or: pnpm run build / npm run build)
*/

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = __dirname;
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist', 'Balloonist.jsx');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

const CORE = [
    'core/paths.jsx',
    'core/json.jsx',
    'core/log.jsx',
    'core/config.jsx',
    'core/geom.jsx',
    'core/id.jsx',
    'core/raster.jsx',
    'core/ops.jsx',
    'core/engine.jsx'
];

const UI = ['ui/panel.jsx'];
const TAIL = ['boot.jsx'];

function read(rel) {
    const p = path.join(SRC, rel);
    if (!fs.existsSync(p)) throw new Error(`missing source: ${rel}`);
    return fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
}

function featureFiles() {
    const dir = path.join(SRC, 'features');
    return fs.readdirSync(dir).filter((f) => f.endsWith('.jsx')).sort();
}

function stamp() {
    const d = new Date();
    const two = (n) => String(n).padStart(2, '0');
    return `${d.getFullYear()}-${two(d.getMonth() + 1)}-${two(d.getDate())} ${two(d.getHours())}:${two(d.getMinutes())}`;
}

const parts = [];
parts.push(`/* ==========================================================================
   Balloonist · 气泡工作台 — InDesign manga lettering plugin
   v${pkg.version} · built ${stamp()} · https://github.com/${pkg.repository ? pkg.repository.replace(/^.*github\.com\//, '').replace(/\.git$/, '') : '…'}
   GENERATED FILE — edit src/ and rebuild, do not edit this file.
   ========================================================================== */`);
parts.push(`(function () {\nvar B = $.global.Balloonist = $.global.Balloonist || {};\nB.VERSION = '${pkg.version}';\nB.BUILD = '${stamp()}';`);

for (const rel of CORE) parts.push(`/* --- ${rel} --- */\n` + read(rel));

const features = featureFiles();
for (const f of features) parts.push(`/* --- features/${f} --- */\n` + read(`features/${f}`));

for (const rel of UI) parts.push(`/* --- ${rel} --- */\n` + read(rel));
for (const rel of TAIL) parts.push(`/* --- ${rel} --- */\n` + read(rel));

parts.push('})();');

const body = parts.join('\n\n');
const header = '#targetengine "balloonist"\n';

/* cheap syntax gate: the wrapped body must parse as JavaScript */
try {
    new vm.Script(body, { filename: 'Balloonist.jsx' });
} catch (err) {
    console.error('[build] syntax error:', err.message);
    process.exit(1);
}

fs.mkdirSync(path.dirname(DIST), { recursive: true });
/* UTF-8 BOM: ExtendScript otherwise decodes the file as the system code page and
   mangles every Chinese/Japanese literal (and can break parsing on quotes). */
fs.writeFileSync(DIST, '\uFEFF' + header + body + '\n', 'utf8');

const lines = (header + body).split('\n').length;
console.log(`[build] dist/Balloonist.jsx  ${lines} lines  ${(fs.statSync(DIST).size / 1024).toFixed(1)} kB`);
console.log(`[build] core ${CORE.length} · features ${features.length} (${features.join(', ')}) · ui ${UI.length}`);
